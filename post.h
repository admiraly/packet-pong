static const char *post_source=
    "#version 120\n"
    "uniform sampler2D scene, previous;\n"
    "uniform int effect;\n"
    "uniform float seconds;\n"
    "float sampleScene(vec2 uv) { return texture2D(scene,uv).r; }\n"
    "void main() {\n"
    "  vec2 uv=gl_TexCoord[0].xy;\n"
    "  vec3 color;\n"
    "  if (effect==1) {\n"
    "    vec2 p=uv*2.0-1.0;\n"
    "    p*=1.0+0.115*dot(p,p);\n"
    "    uv=p*0.5+0.5;\n"
    "    float mask=step(max(abs(p.x),abs(p.y)),1.0);\n"
    "    float scan=0.72+0.28*cos(uv.y*1696.46);\n"
    "    color=vec3(sampleScene(uv)*mask*scan);\n"
    "  } else if (effect==2) {\n"
    "    vec2 split=vec2(0.007+0.003*sin(seconds*4.0),0.003);\n"
    "    color=vec3(sampleScene(uv+split),sampleScene(uv),sampleScene(uv-split));\n"
    "  } else if (effect==3) {\n"
    "    float glow=0.0;\n"
    "    for (int x=-2;x<=2;++x) for (int y=-2;y<=2;++y)\n"
    "      glow+=sampleScene(uv+vec2(float(x)/240.0,float(y)/135.0));\n"
    "    float ghost=texture2D(previous,uv).r;\n"
    "    color=vec3(max(sampleScene(uv),ghost*0.45)+glow*0.034);\n"
    "  } else if (effect==4) {\n"
    "    float band=floor(uv.y*29.0);\n"
    "    float hash=fract(sin(band*33.7+floor(seconds*12.0)*6.7)*43758.54);\n"
    "    uv.x+=sin(uv.y*31.0+seconds*7.0)*0.008+(hash-0.5)*step(0.90,hash)*0.11;\n"
    "    color=vec3(sampleScene(uv));\n"
    "  } else color=vec3(sampleScene(uv));\n"
    "  gl_FragColor=vec4(color,1.0);\n"
    "}\n";
